-- 3. Create public.document_scopes matching actual documents/taxonomy PK types
--    (handles bigint OR uuid dynamically) & backfill from legacy documents cols
-- ============================================================================
do $$
declare
    v_doc_type text;
    v_zone_type text;
    v_div_type text;
    v_dept_type text;
    v_has_zone_col boolean;
    v_has_div_col boolean;
    v_has_dept_col boolean;
    v_has_scope_col boolean;
    v_zone_expr text;
    v_div_expr text;
    v_dept_expr text;
    v_scope_expr text;
begin
    select format_type(a.atttypid, a.atttypmod) into v_doc_type
    from pg_attribute a
    where a.attrelid = 'public.documents'::regclass and a.attname = 'id' and not a.attisdropped;

    select format_type(a.atttypid, a.atttypmod) into v_zone_type
    from pg_attribute a
    where a.attrelid = 'public.zones'::regclass and a.attname = 'id' and not a.attisdropped;

    select format_type(a.atttypid, a.atttypmod) into v_div_type
    from pg_attribute a
    where a.attrelid = 'public.divisions'::regclass and a.attname = 'id' and not a.attisdropped;

    select format_type(a.atttypid, a.atttypmod) into v_dept_type
    from pg_attribute a
    where a.attrelid = 'public.departments'::regclass and a.attname = 'id' and not a.attisdropped;

    if to_regclass('public.document_scopes') is null then
        execute format(
            $sql$
            create table public.document_scopes (
                id bigint generated by default as identity primary key,
                document_id %1$s not null references public.documents(id) on delete cascade,
                scope_level text not null check (
                    scope_level in ('DEPARTMENT', 'DIVISION', 'ZONE', 'RAILWAY_BOARD', 'COMMON')
                ),
                zone_id %2$s references public.zones(id) on delete cascade,
                division_id %3$s references public.divisions(id) on delete cascade,
                department_id %4$s references public.departments(id) on delete cascade,
                created_at timestamptz not null default now()
            )
            $sql$,
            v_doc_type,
            v_zone_type,
            v_div_type,
            v_dept_type
        );
    end if;

    -- Backfill document_scopes for existing documents that have no scope row yet
    select exists (
        select 1 from information_schema.columns
        where table_schema = 'public' and table_name = 'documents' and column_name = 'zone_id'
    ) into v_has_zone_col;

    select exists (
        select 1 from information_schema.columns
        where table_schema = 'public' and table_name = 'documents' and column_name = 'division_id'
    ) into v_has_div_col;

    select exists (
        select 1 from information_schema.columns
        where table_schema = 'public' and table_name = 'documents' and column_name = 'department_id'
    ) into v_has_dept_col;

    select exists (
        select 1 from information_schema.columns
        where table_schema = 'public' and table_name = 'documents' and column_name = 'scope_level'
    ) into v_has_scope_col;

    v_zone_expr := case when v_has_zone_col then 'd.zone_id' else format('null::%s', v_zone_type) end;
    v_div_expr := case when v_has_div_col then 'd.division_id' else format('null::%s', v_div_type) end;
    v_dept_expr := case when v_has_dept_col then 'd.department_id' else format('null::%s', v_dept_type) end;

    if v_has_scope_col then
        v_scope_expr := $s$
            case
                when upper(coalesce(d.scope_level, '')) in ('DEPARTMENT', 'DIVISION', 'ZONE', 'RAILWAY_BOARD', 'COMMON')
                    then upper(d.scope_level)
                when %1$s is not null and %3$s is not null then 'DEPARTMENT'
                when %1$s is not null and %2$s is not null then 'DIVISION'
                when %1$s is not null then 'ZONE'
                else 'RAILWAY_BOARD'
            end
        $s$;
    else
        v_scope_expr := $s$
            case
                when %1$s is not null and %3$s is not null then 'DEPARTMENT'
                when %1$s is not null and %2$s is not null then 'DIVISION'
                when %1$s is not null then 'ZONE'
                else 'RAILWAY_BOARD'
            end
        $s$;
    end if;

    v_scope_expr := format(v_scope_expr, v_zone_expr, v_div_expr, v_dept_expr);

    execute format(
        $sql$
        insert into public.document_scopes (document_id, scope_level, zone_id, division_id, department_id)
        select
            d.id,
            %1$s,
            %2$s,
            %3$s,
            %4$s
        from public.documents d
        where not exists (
            select 1 from public.document_scopes ds where ds.document_id = d.id
        )
        $sql$,
        v_scope_expr,
        v_zone_expr,
        v_div_expr,
        v_dept_expr
    );
end $$;

create index if not exists idx_doc_scopes_lookup
    on public.document_scopes (scope_level, zone_id, division_id, department_id);

