-- ============================================================================
-- 6. Production Hybrid 5-Tier Hierarchical Search RPC
--    * Uses text for zone/division/department & returned chunk_id/document_id
--      so BOTH bigint and uuid primary keys work without type mismatch.
--    * Uses rc.search_tsv (no dependency on legacy rc.content_tsv).
-- ============================================================================
drop function if exists public.search_railway_rules(vector(1536), text, uuid, uuid, uuid, int);
drop function if exists public.search_railway_rules(vector(768), text, uuid, uuid, uuid, int);
drop function if exists public.search_railway_rules(vector(768), text, bigint, bigint, bigint, int);
drop function if exists public.search_railway_rules(vector(1536), text, bigint, bigint, bigint, int);
drop function if exists public.search_railway_rules(vector(1024), text, text, text, text, int);

create or replace function public.search_railway_rules(
    query_embedding vector(1024),
    query_text text,
    p_zone_id text,
    p_division_id text,
    p_department_id text,
    match_limit int default 18
)
returns table (
    chunk_id text,
    document_id text,
    document_title text,
    document_number text,
    document_type text,
    issuing_authority text,
    authority_rank int,
    issue_date date,
    effective_date date,
    page_number int,
    rule_number text,
    chapter text,
    section_title text,
    content text,
    search_tier int,
    search_tier_label text,
    is_superseded boolean,
    superseded_by_ref text,
    vector_score double precision,
    keyword_score double precision,
    similarity_score double precision
)
language sql
stable
security definer
set search_path = public, extensions
as $$
    with cleaned_query as (
        select
            nullif(trim(coalesce(query_text, '')), '') as q_raw,
            plainto_tsquery('english', coalesce(query_text, '')) as q_eng,
            plainto_tsquery('simple', coalesce(query_text, '')) as q_simple
    ),
    scoped_docs as (
        select
            d.id as doc_id,
            min(
                case
                    -- Tier 1: Selected Department + Selected Division + Selected Zone
                    when ds.scope_level = 'DEPARTMENT'
                         and ds.zone_id::text = p_zone_id
                         and ds.division_id::text = p_division_id
                         and ds.department_id::text = p_department_id then 1
                    -- Tier 2: Selected Department + Selected Zone (Zone-wide Departmental)
                    when ds.scope_level = 'DEPARTMENT'
                         and ds.zone_id::text = p_zone_id
                         and ds.division_id is null
                         and ds.department_id::text = p_department_id then 2
                    -- Tier 3: Other Departments in Selected Division / Division-wide
                    when ds.scope_level in ('DEPARTMENT', 'DIVISION')
                         and ds.zone_id::text = p_zone_id
                         and ds.division_id::text = p_division_id then 3
                    -- Tier 4: Entire Selected Zone
                    when ds.scope_level = 'ZONE'
                         and ds.zone_id::text = p_zone_id then 4
                    -- Tier 5: Railway Board & Common Railway Documents
                    else 5
                end
            ) as tier
        from public.documents d
        join public.document_scopes ds on ds.document_id = d.id
        where coalesce(d.status, 'published') in ('published', 'superseded', 'active')
          and d.ingestion_status = 'completed'
          and (
              (ds.scope_level = 'DEPARTMENT'
               and ds.zone_id::text = p_zone_id
               and ds.department_id::text = p_department_id
               and (ds.division_id is null or ds.division_id::text = p_division_id))
              or (ds.scope_level in ('DEPARTMENT', 'DIVISION')
                  and ds.zone_id::text = p_zone_id
                  and ds.division_id::text = p_division_id)
              or (ds.scope_level = 'ZONE'
                  and ds.zone_id::text = p_zone_id)
              or (ds.scope_level in ('RAILWAY_BOARD', 'COMMON')
                  and (ds.zone_id is null or ds.zone_id::text = p_zone_id))
          )
        group by d.id
    ),
    scored as (
        select
            rc.id::text as chunk_id,
            d.id::text as document_id,
            d.title as document_title,
            d.document_number,
            d.document_type,
            d.issuing_authority,
            d.authority_rank,
            d.issue_date,
            d.effective_date,
            rc.page_number,
            rc.rule_number,
            rc.chapter,
            rc.section_title,
            rc.content,
            sd.tier as search_tier,
            case sd.tier
                when 1 then 'Selected Dept + Division + Zone'
                when 2 then 'Selected Dept + Zone'
                when 3 then 'Selected Division (Other Dept)'
                when 4 then 'Zone-Wide'
                else 'Railway Board / Common'
            end as search_tier_label,
            (
                d.status = 'superseded'
                or exists (
                    select 1
                    from public.amendments a
                    where a.target_document_id = d.id
                      and upper(coalesce(a.relationship_type, '')) in ('SUPERSEDES', 'REPEALS')
                )
            ) as is_superseded,
            (
                select string_agg(coalesce(ad.document_number, ad.title, a.circular_reference), '; ')
                from public.amendments a
                left join public.documents ad on ad.id = a.amending_document_id
                where a.target_document_id = d.id
            ) as superseded_by_ref,
            greatest(0.0, 1.0 - (rc.embedding_bge_m3 <=> query_embedding))::double precision as vector_score,
            (
                case
                    when cq.q_raw is null then 0.0
                    else (
                        coalesce(ts_rank_cd(rc.search_tsv, cq.q_simple), 0.0) * 0.60
                        + coalesce(ts_rank_cd(rc.search_tsv, cq.q_eng), 0.0) * 0.40
                        + case
                            when nullif(trim(coalesce(rc.rule_number, '')), '') is not null
                                 and lower(cq.q_raw) like '%' || lower(trim(rc.rule_number)) || '%'
                            then 0.70
                            else 0.0
                          end
                        + case
                            when nullif(trim(coalesce(d.document_number, '')), '') is not null
                                 and lower(cq.q_raw) like '%' || lower(trim(d.document_number)) || '%'
                            then 0.55
                            else 0.0
                          end
                    )
                end
            )::double precision as keyword_score
        from public.rule_chunks rc
        join public.documents d on d.id = rc.document_id
        join scoped_docs sd on sd.doc_id = d.id
        cross join cleaned_query cq
        where rc.embedding_bge_m3 is not null
    )
    select
        s.chunk_id,
        s.document_id,
        s.document_title,
        s.document_number,
        s.document_type,
        s.issuing_authority,
        s.authority_rank,
        s.issue_date,
        s.effective_date,
        s.page_number,
        s.rule_number,
        s.chapter,
        s.section_title,
        s.content,
        s.search_tier,
        s.search_tier_label,
        s.is_superseded,
        s.superseded_by_ref,
        s.vector_score,
        s.keyword_score,
        (
            0.68 * s.vector_score
            + 0.32 * least(1.0, s.keyword_score)
        )::double precision as similarity_score
    from scored s
    order by
        similarity_score desc,
        s.is_superseded asc,
        s.authority_rank desc,
        s.effective_date desc nulls last,
        s.search_tier asc
    limit greatest(1, least(coalesce(match_limit, 18), 50));
$$;

revoke all on function public.search_railway_rules(vector(1024), text, text, text, text, int) from public;
revoke all on function public.search_railway_rules(vector(1024), text, text, text, text, int) from anon;
