    elsif exists (select 1 from information_schema.columns where table_schema='public' and table_name='amendments' and column_name='parent_document_id') then
        execute 'update public.amendments set target_document_id = parent_document_id where target_document_id is null and parent_document_id is not null';
    elsif exists (select 1 from information_schema.columns where table_schema='public' and table_name='amendments' and column_name='document_id') then
        execute 'update public.amendments set target_document_id = document_id where target_document_id is null and document_id is not null';
    end if;

    -- Backfill relationship_type from legacy amendment_type / type if present
    if exists (select 1 from information_schema.columns where table_schema='public' and table_name='amendments' and column_name='amendment_type') then
        execute $sql$
            update public.amendments
            set relationship_type = case
                when upper(coalesce(amendment_type, '')) in ('AMENDS', 'SUPERSEDES', 'CLARIFIES', 'PARTIALLY_MODIFIES', 'REPEALS')
                    then upper(amendment_type)
                when upper(coalesce(amendment_type, '')) like '%SUPERSEDE%' then 'SUPERSEDES'
                when upper(coalesce(amendment_type, '')) like '%REPEAL%' then 'REPEALS'
                else coalesce(relationship_type, 'AMENDS')
            end
            where relationship_type is null or relationship_type = ''
        $sql$;
    end if;

    -- Backfill circular_reference from legacy circular_number / amendment_number if present
    if exists (select 1 from information_schema.columns where table_schema='public' and table_name='amendments' and column_name='circular_number') then
        execute 'update public.amendments set circular_reference = circular_number where circular_reference is null and circular_number is not null';
    elsif exists (select 1 from information_schema.columns where table_schema='public' and table_name='amendments' and column_name='amendment_number') then
        execute 'update public.amendments set circular_reference = amendment_number where circular_reference is null and amendment_number is not null';
    end if;

    -- Relax NOT NULL on non-canonical legacy columns in amendments so new inserts never fail
    for col_rec in
        select column_name
        from information_schema.columns
        where table_schema = 'public'
          and table_name = 'amendments'
          and is_nullable = 'NO'
          and column_default is null
          and column_name not in (
              'id', 'amending_document_id', 'target_document_id',
              'relationship_type', 'created_at'
          )
    loop
        execute format('alter table public.amendments alter column %I drop not null', col_rec.column_name);
    end loop;
end $$;

