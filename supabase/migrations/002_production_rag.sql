-- Backfill documents.chunk_count and mark completed ONLY where 1024-dim BGE-M3 embeddings exist
update public.documents d
set
    chunk_count = coalesce(sub.total_cnt, 0),
    ingestion_status = case
        when coalesce(sub.bge_cnt, 0) > 0 then 'completed'
        else d.ingestion_status
    end,
    indexed_at = coalesce(
        d.indexed_at,
        case when coalesce(sub.bge_cnt, 0) > 0 then now() else null end
    )
from (
    select
        document_id,
        count(*)::int as total_cnt,
        count(embedding_bge_m3)::int as bge_cnt
    from public.rule_chunks
    group by document_id
) sub
where d.id = sub.document_id;

